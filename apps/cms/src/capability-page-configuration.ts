export async function ensureCapabilityPageConfiguration(strapi: any) {
  const documents = strapi.documents(CAPABILITY_PAGE_UID);
  const [existingPage, publicRole] = await Promise.all([
    documents.findFirst(),
    strapi.db
      .query("plugin::users-permissions.role")
      .findOne({ where: { type: "public" }, populate: ["permissions"] }),
  ]);

  if (!publicRole) throw new Error("Public role was not found");

  const operations: Promise<unknown>[] = [];
  if (!existingPage) {
    operations.push(
      documents.create({
        data: DEFAULT_CAPABILITY_PAGE,
        status: "published",
      }),
    );
  }

  const hasPermission = (publicRole.permissions ?? []).some(
    (permission: { action?: string }) =>
      permission.action === CAPABILITY_PAGE_PERMISSION_ACTION,
  );
  if (!hasPermission) {
    operations.push(
      strapi.db.query("plugin::users-permissions.permission").create({
        data: {
          action: CAPABILITY_PAGE_PERMISSION_ACTION,
          role: publicRole.id,
        },
      }),
    );
  }

  await Promise.all(operations);
}
